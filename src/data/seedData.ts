export function buildSeedAuditLogs(ownerId: string, items: InventoryItem[], petugas: string): AuditLog[] {
  const baseTime = Date.now();
  const sampleItems = items.slice(0, 5);
  const actions: Array<{ aksi: AuditLog['aksi']; catatan: string }> = [
    { aksi: 'Audit Kondisi', catatan: 'Verifikasi fisik semester ganjil selesai, jumlah sesuai daftar KIB.' },
    { aksi: 'Tambah Barang', catatan: 'Pencatatan aset baru sumber dana BOS Reguler ke sistem inventaris.' },
    { aksi: 'Audit Kondisi', catatan: 'Pemeriksaan unit komputer Lab TIK menjelang pelaksanaan ANBK.' },
    { aksi: 'Perbarui Data', catatan: 'Pembaruan catatan kerusakan ringan pada roller printer ruang guru.' },
    { aksi: 'Audit Kondisi', catatan: 'Penandaan barang rusak berat di Gudang Sarpras untuk usulan penghapusan.' },
  ];

  return sampleItems.map((item, idx) => ({
    id: `log_seed_0${idx + 1}_${ownerId.slice(0, 8)}`,
    itemId: item.id,
    kodeBarang: item.kodeBarang,
    namaBarang: item.namaBarang,
    aksi: actions[idx].aksi,
    catatan: actions[idx].catatan,
    petugas,
    ownerId,
    createdAt: new Date(baseTime - idx * 86400000 * 2).toISOString(),
  }));
}
